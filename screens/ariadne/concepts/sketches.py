#!/usr/bin/env python3
"""ariadne, round 1: three subjects for the function track's screen, drawn as rough 1:1 sketches to choose from.

Shared fake data: the target track's 16 steps over the last 5 passes. Each step is empty or a note (pitch 0..12);
steps 2, 6 and 11 are p-locked (parameter locks, drawn their own way); steps 3, 9 and 14 are autogenerated: a function
rewrote them, so they differ pass to pass; the rest are locked: they stay as written.

    python3 sketches.py <outdir>     → a.svg b.svg c.svg and sketches.png (1:1 frames stacked)
"""
import math
import random
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "meikyu" / "concepts"))
import orbits as O                       # noqa: E402  path / ell helpers
import pages as P                        # noqa: E402  stock header

path, ell = O.path, O.ell
G = lambda v: f"#{v:02X}{v:02X}{v:02X}"
rnd = random.Random(4)
BASE = [5, None, 8, 3, None, 7, 5, None, 10, 2, None, 6, None, 9, 4, None]
PLOCK = {2, 6, 11}
AUTO = {3, 9, 14}
PASSES = []
for k in range(5):
    row = list(BASE)
    for s in AUTO:
        row[s] = rnd.choice([None, rnd.randint(0, 12)])
    PASSES.append(row)                   # PASSES[-1] is the pass playing now
HEAD = 6                                 # the step playing


def header(labels=("targ", "amt", "rate", "hold"), vals=("T3", "40", "1/16", "mom")):
    p = P.Page(density=0.4, scale=0, corrupt=0.2, drum=False)
    o = P.header(p)
    for a, b in zip(("Dens", "Scal", "Crpt", "Drum"), labels):
        o = [l.replace(f">{a}<", f">{b}<") for l in o]
    for a, b in zip(("40", "minor", "20", "off"), vals):
        o = [l.replace(f">{a}<", f">{b}<", 1) for l in o]
    return o


def frame(body, name, out):
    svg = "\n".join(['<svg xmlns="http://www.w3.org/2000/svg" width="480" height="220" viewBox="0 0 480 220">',
                     '<rect x="0" y="0" width="480" height="220" fill="#000000" stroke="none"/>'] + body + header() + ["</svg>"])
    (out / f"{name}.svg").write_text(svg)
    subprocess.run(["rsvg-convert", "-w", "480", "-h", "220", str(out / f"{name}.svg"), "-o", str(out / f"{name}.png")], check=True)


def knot(x, y, s, g, plock, hot=False):
    """a note: a filled bead; a p-locked note: a bead with a tie bar through it"""
    o = [path(ell(x, y, s, s, n=16), G(0xCD if hot else g), 1.0, fill=G(0xCD if hot else g), close=True)]
    if plock:
        o.append(path([(x - s - 3, y - s - 1), (x + s + 3, y + s + 1)], G(0xCD), 1.4))
        o.append(path(ell(x, y, s + 2.5, s + 2.5, n=16), G(0x96), 1.0, close=True))
    return o


# ---- A · rings of passes: the thread winds outward, one ring per pass ------------------------------------------------
def sketch_a():
    cx, cy = 240, 122
    o = [path(ell(cx, cy, 16, 16, n=24), G(0x4B), 1.2, close=True)]           # the centre, where the thread starts
    for k, row in enumerate(PASSES):
        r = 30 + 17 * k
        cur = k == len(PASSES) - 1
        g_ring = 0x7D if cur else 0x32 + 8 * k
        o.append(path(ell(cx, cy, r, r * 0.92, n=60), G(g_ring), 1.4 if cur else 1.0, close=True))
        for s, note in enumerate(row):
            a = -math.pi / 2 + 2 * math.pi * s / 16
            x, y = cx + r * math.cos(a), cy + 0.92 * r * math.sin(a)
            if note is None:
                continue
            g = 0xAF if cur else 0x4B + 10 * k
            if s in AUTO:                                                      # rewritten this pass: hollow
                o.append(path(ell(x, y, 2.6, 2.6, n=12), G(g), 1.2, fill="#000000", close=True))
            else:
                o += knot(x, y, 2.6 if cur else 2.0, g, s in PLOCK and cur, cur and s == HEAD)
    a = -math.pi / 2 + 2 * math.pi * HEAD / 16                                 # the playhead: the thread's end
    o.append(path([(cx + 18 * math.cos(a), cy + 18 * math.sin(a)), (cx + 110 * math.cos(a), cy + 0.92 * 110 * math.sin(a))], G(0x96), 1.0))
    return o


# ---- B · a loom: steps are warp threads, each pass weaves a new row ---------------------------------------------------
def sketch_b():
    x0, dx, y0, dy = 64, 22, 196, 26
    o = []
    for s in range(16):                                                        # warp threads
        x = x0 + dx * s
        o.append(path([(x, 40), (x, 204)], G(0x32), 1.0))
    for k, row in enumerate(PASSES):
        y = y0 - dy * (len(PASSES) - 1 - k)
        cur = k == len(PASSES) - 1
        o.append(path([(x0 - 14, y), (x0 + dx * 15 + 14, y)], G(0x64 if cur else 0x32), 1.0))   # the weft
        for s, note in enumerate(row):
            if note is None:
                continue
            x = x0 + dx * s
            h = 4 + note * 0.9                                                 # pitch as the float's length
            g = 0xAF if cur else 0x64 - 6 * (len(PASSES) - 1 - k)
            if s in AUTO:
                o.append(path([(x - 5, y - h / 2), (x + 5, y - h / 2), (x + 5, y + h / 2), (x - 5, y + h / 2)], G(g), 1.0, fill="#000000", close=True))
            else:
                o.append(path([(x - 5, y - h / 2), (x + 5, y - h / 2), (x + 5, y + h / 2), (x - 5, y + h / 2)], G(g), 0.6, fill=G(0xCD if cur and s == HEAD else g), close=True))
                if s in PLOCK and cur:
                    o.append(path(ell(x, y - h / 2 - 6, 2.4, 2.4, n=12), G(0xCD), 1.0, fill=G(0xCD), close=True))
    x = x0 + dx * HEAD
    o.append(path([(x - 9, 206), (x, 200), (x + 9, 206)], G(0x96), 1.2, close=True))   # the shuttle under the step playing
    return o


# ---- C · one thread across the page, notes hung on it at their pitch --------------------------------------------------
def sketch_c():
    x0, dx, ty = 36, 27, 64
    o = [path([(16, ty), (464, ty)], G(0x96), 1.4)]
    for s, note in enumerate(PASSES[-1]):
        x = x0 + dx * s
        o.append(path([(x, ty - 3), (x, ty + 3)], G(0x4B), 1.0))
        if note is None:
            continue
        y = ty + 24 + (12 - note) * 8
        ghost = [r[s] for r in PASSES[:-1]]
        for k, gn in enumerate(ghost):                                          # earlier passes, faint, behind
            if gn is not None and gn != note:
                gy = ty + 24 + (12 - gn) * 8
                o.append(path(ell(x, gy, 2.0, 2.0, n=12), G(0x32 + 6 * k), 1.0, close=True))
        o.append(path([(x, ty), (x, y)], G(0x64 if s not in AUTO else 0x4B), 1.0))
        if s in AUTO:
            o.append(path(ell(x, y, 3.4, 3.4, n=14), G(0xAF), 1.2, fill="#000000", close=True))
        else:
            o += knot(x, y, 3.4, 0xAF, s in PLOCK, s == HEAD)
    return o


def main():
    out = Path(sys.argv[1])
    out.mkdir(parents=True, exist_ok=True)
    from PIL import Image
    ims = []
    for name, fn in (("a", sketch_a), ("b", sketch_b), ("c", sketch_c)):
        frame(fn(), name, out)
        ims.append(Image.open(out / f"{name}.png"))
    sheet = Image.new("RGB", (480, 3 * 230), "#1A1A1A")
    for k, im in enumerate(ims):
        sheet.paste(im, (0, k * 230))
    sheet.save(Path(__file__).resolve().parent / "sketches.png")


if __name__ == "__main__":
    main()
