HAIR, LINE, SUBJ = 1.0, 1.5, 2.0   # craft.md line weights
FONT = "UniversNextPro-Light"

# Defaults from definition.json, shown in the stock header.
DEFAULTS = {"press": 0.5, "reed": 0.4, "leak": 0.0, "choir": 0.0}
