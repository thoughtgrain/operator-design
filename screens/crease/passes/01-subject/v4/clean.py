#!/usr/bin/env python3
"""Crease v4 (P1 section drawing, engineering schematic): cleanup of the rest sketch.

    python3 screens/crease/passes/01-subject/v4/clean.py

Writes clean.svg next to this file (render: rsvg-convert -w 480 -h 220 -b black
clean.svg -o clean.png). Same idea and composition as sketch.py's v4: a folding
press in section, the web festooned over a fixed upper roller bank and under a
lower bank that drives down by crease. Cleanup only: no text in the drawing, the
web runs on true tangents round each roller with a clear gap, the infeed nip and
diverter keep clear of the web, the dimension carries ticks instead of a letter.
Model and primitives copied from ../sketch.py.
"""
from __future__ import annotations

import math
from pathlib import Path

HERE = Path(__file__).resolve().parent
W, H = 480, 220

BRIGHT, G175, G150, G125, G100, G75, G50 = ("#CDCDCD", "#AFAFAF", "#969696", "#7D7D7D",
                                           "#646464", "#4B4B4B", "#323232")
BLACK = "#000000"
HAIR, LINE, SUBJ = 1.0, 1.5, 2.5   # craft.md line weights
FONT = "UniversNextPro-Light"

P = {"crease": 0.3333, "sym": 0.5, "paper": 0.4, "mix": 1.0}
LABELS = ["crease", "sym", "paper", "mix"]
CAPTIONS = ["2.00", "0", "40", "100"]


# ---------------------------------------------------------------- the effect's model (from sketch.py)
def gain(p=P):
    return 8 ** p["crease"]


def bias(p=P):
    return -1 + 2 * p["sym"]


# ---------------------------------------------------------------- SVG frame (from sketch.py)
def n(v: float) -> str:
    s = f"{v:.2f}".rstrip("0").rstrip(".")
    return "0" if s in ("-0", "") else s


class Frame:
    def __init__(self) -> None:
        self.parts: list[str] = []
        self.node = 0

    def _id(self, bound: bool) -> str:
        if not bound:
            return ""
        i = self.node
        self.node += 1
        return f' id="crease_node_{i}"'

    def poly(self, pts, fill="none", stroke=BRIGHT, sw=SUBJ, bound=False) -> None:
        pts = dedupe(pts)
        assert 3 <= len(pts) <= 64, len(pts)
        d = "M " + " L ".join(f"{n(x)} {n(y)}" for x, y in pts) + " Z"
        st = f'stroke="{stroke}" stroke-width="{n(sw)}"' if stroke != "none" else 'stroke="none"'
        self.parts.append(f'<path{self._id(bound)} d="{d}" fill="{fill}" {st}/>')

    def line(self, pts, w=HAIR, colour=G100, bound=False) -> None:
        pts = dedupe(pts)
        for chunk in chunks(pts, 31):
            if len(chunk) >= 2:
                self.poly(ribbon(chunk, w), fill=colour, stroke="none", bound=bound)

    def circle(self, cx, cy, r, fill=BLACK, stroke=G100, sw=HAIR, bound=False) -> None:
        st = f'stroke="{stroke}" stroke-width="{n(sw)}"' if stroke != "none" else 'stroke="none"'
        self.parts.append(f'<circle{self._id(bound)} cx="{n(cx)}" cy="{n(cy)}" r="{n(r)}" fill="{fill}" {st}/>')

    def svg(self, title: str) -> str:
        palette = "\n  ".join(
            f'<path id="crease_palette_{i}" d="M {700 + 10 * i} 300 L {704 + 10 * i} 300 L {704 + 10 * i} 304 Z" '
            f'fill="{c}" stroke="{c}" stroke-width="2"/>'
            for i, c in enumerate([BRIGHT, G150, G100, G75, G50, BLACK]))
        body = "\n  ".join(self.parts)
        return (f'<svg xmlns="http://www.w3.org/2000/svg" width="{W}" height="{H}" viewBox="0 0 {W} {H}">\n'
                f'  <!-- crease · subject pass 01 · {title} · rest (defaults, no notes). Generated by clean.py -->\n'
                f'  <g id="preview_canvas">\n    <rect x="0" y="0" width="480" height="220" fill="#000000" stroke="none"/>\n  </g>\n'
                f'{header()}\n  {palette}\n  {body}\n</svg>\n')


def dedupe(pts):
    out_ = []
    for p in pts:
        p = (round(p[0], 2), round(p[1], 2))
        if not out_ or math.dist(out_[-1], p) >= 0.3:
            out_.append(p)
    if len(out_) > 2 and math.dist(out_[0], out_[-1]) < 0.3:
        out_.pop()
    return out_


def chunks(pts, size):
    if len(pts) <= size:
        yield pts
        return
    i = 0
    while i < len(pts) - 1:
        yield pts[i:i + size]
        i += size - 1


def norm(v):
    l = math.hypot(*v) or 1.0
    return (v[0] / l, v[1] / l)


def ribbon(pts, w):
    h = w / 2
    left, right = [], []
    for i, p in enumerate(pts):
        if i == 0:
            nx, ny = norm((-(pts[1][1] - p[1]), pts[1][0] - p[0]))
            m = 1.0
        elif i == len(pts) - 1:
            nx, ny = norm((-(p[1] - pts[i - 1][1]), p[0] - pts[i - 1][0]))
            m = 1.0
        else:
            a = norm((p[0] - pts[i - 1][0], p[1] - pts[i - 1][1]))
            b = norm((pts[i + 1][0] - p[0], pts[i + 1][1] - p[1]))
            n1, n2 = (-a[1], a[0]), (-b[1], b[0])
            nx, ny = norm((n1[0] + n2[0], n1[1] + n2[1]))
            cos = nx * n1[0] + ny * n1[1]
            m = min(1 / max(cos, 1e-3), 2.0)
        left.append((p[0] + nx * h * m, p[1] + ny * h * m))
        right.append((p[0] - nx * h * m, p[1] - ny * h * m))
    return left + right[::-1]


def header() -> str:
    steps = [BLACK, G50, G75, G100, G125, G150, G175, BRIGHT]
    rows = [f'    <rect x="{60 * i}" y="0" width="60" height="20" fill="{c}" stroke="none"/>' for i, c in enumerate(steps)]
    for i, label in enumerate(LABELS):
        ink = "#CBCBCB" if i < 2 else BLACK
        rows.append(f'    <text transform="matrix(1 0 0 1 {5 + 120 * i} 10)" fill="{ink}" stroke="none" '
                    f'font-family="{FONT}" font-size="10px">{label}</text>')
        rows.append(f'    <text transform="matrix(1 0 0 1 {65 + 120 * i} 17.44)" fill="{ink}" stroke="none" '
                    f'font-family="{FONT}" font-size="20px">{CAPTIONS[i]}</text>')
    return '  <g id="preview_header">\n' + "\n".join(rows) + "\n  </g>"


# ---------------------------------------------------------------- web geometry: true tangents
def tangent(a, b, R, sa, sb):
    """Common tangent between circles a and b (equal radius R) for a web that travels round a with
    orientation sa and round b with sb (+1: angle increasing in screen coords, i.e. clockwise on
    screen). Returns the angles on a and b where the straight run leaves a and meets b."""
    dx, dy = b[0] - a[0], b[1] - a[1]
    L = math.hypot(dx, dy)
    al = math.atan2(dy, dx)
    best = None
    if sa != sb:      # internal tangent: normals opposite, d . n_a = 2R
        for sgn in (1, -1):
            phi = al + sgn * math.acos(min(1.0, 2 * R / L))
            na = (math.cos(phi), math.sin(phi))
            pa = (a[0] + R * na[0], a[1] + R * na[1])
            pb = (b[0] - R * na[0], b[1] - R * na[1])
            ta = (-sa * na[1], sa * na[0])
            if (pb[0] - pa[0]) * ta[0] + (pb[1] - pa[1]) * ta[1] > 0:
                best = (phi, phi + math.pi)
    else:             # external tangent: same normal, perpendicular to d
        for sgn in (1, -1):
            phi = al + sgn * math.pi / 2
            na = (math.cos(phi), math.sin(phi))
            ta = (-sa * na[1], sa * na[0])
            if dx * ta[0] + dy * ta[1] > 0:
                best = (phi, phi)
    return best


def wrap(c, R, a0, a1, s, step=math.radians(36)):
    """Points round circle c from angle a0 to a1 travelling with orientation s, ~step apart."""
    span = (a1 - a0) * s % (2 * math.pi)
    k = max(1, math.ceil(span / step))
    return [(c[0] + R * math.cos(a0 + s * span * i / k), c[1] + R * math.sin(a0 + s * span * i / k)) for i in range(k + 1)]


# ---------------------------------------------------------------- v4 · P1 section drawing, engineering schematic
def v4() -> Frame:
    f = Frame()
    g, b, paper, mix = gain(), bias(), P["paper"], P["mix"]
    upper_y = 72
    depth = 12 + 108 * math.log(g) / math.log(8)          # crease: 12 px (x1) .. 120 px (x8)
    lower_y = upper_y + depth
    r = 4 + 10 * paper                                     # paper: sharp crease r 4 .. soft bend r 14
    gap = 3.2                                              # black between roller rim and web, at every paper
    R = r + gap                                            # the web's centre line round a roller
    xs_up = [150, 222, 294, 366]
    shift = b * 26                                         # sym: lower bank slides off-centre
    xs_lo = [186 + shift, 258 + shift, 330 + shift]
    web_y = upper_y - R                                    # the web's run-in and run-out height
    rail_up = upper_y - 30
    rail_lo = min(lower_y + 32, 204)

    # Mounting rails: a Line-weight rail with the section's ground hatch, 45 degrees, 8 px apart.
    for yy, up in ((rail_up, True), (rail_lo, False)):
        f.line([(124, yy), (392, yy)], w=LINE, colour=G100)
        for x in range(132, 392, 8):
            y0 = yy - 1.5 if up else yy + 1.5
            f.line([(x, y0), (x - 5, y0 - 5 if up else y0 + 5)], w=HAIR, colour=G75)
    # Hangers from the rails to the roller rims (centre lines), stopping short of the web.
    for x in xs_up:
        f.line([(x, rail_up + 1), (x, upper_y - R - 4)], w=HAIR, colour=G75)
    for x in xs_lo:
        f.line([(x, lower_y + R + 4), (x, rail_lo - 1)], w=HAIR, colour=G75, bound=True)

    # The web: in level from the nip, over each upper roller (clockwise), under each lower one
    # (anticlockwise), out level from the top of the last upper roller. Common tangents throughout.
    circles = []
    for i, xu in enumerate(xs_up):
        circles.append(((xu, upper_y), 1))
        if i < len(xs_lo):
            circles.append(((xs_lo[i], lower_y), -1))
    top = -math.pi / 2
    spans, enter = [], top
    for k, (c, s) in enumerate(circles):
        if k + 1 < len(circles):
            leave, nxt = tangent(c, circles[k + 1][0], R, s, circles[k + 1][1])
        else:
            leave, nxt = top, None
        spans.append((c, s, enter, leave))
        enter = nxt
    web = [(30, web_y)]
    for c, s, a0, a1 in spans:
        web += wrap(c, R, a0, a1, s, math.radians(30))
    web.append((450, web_y))
    web = dedupe(web)
    # Round turns need ~55 centre points: two mutable outlines of <= 31 (62 ribbon points each),
    # where the sketch squeezed one into 31 and the turns went polygonal.
    assert len(web) <= 61, len(web)
    f.line(web, w=SUBJ, colour=BRIGHT, bound=True)

    # Rollers in section: black body, Line rim, centre cross at Hairline.
    for x, y, bound in [(x, upper_y, False) for x in xs_up] + [(x, lower_y, True) for x in xs_lo]:
        f.circle(x, y, r, fill=BLACK, stroke=G150, sw=LINE, bound=True)
        f.line([(x - 3.5, y), (x + 3.5, y)], w=HAIR, colour=G100, bound=bound)
        f.line([(x, y - 3.5), (x, y + 3.5)], w=HAIR, colour=G100, bound=bound)

    # Infeed nip: two rollers either side of the web, a clear gap to it.
    nip_x, nr = 64, 5
    for sgn in (-1, 1):
        f.circle(nip_x, web_y + sgn * (nr + 3.5), nr, fill=BLACK, stroke=G125, sw=LINE)
    # Mix diverter (sketch.py's mapping): at 100 % the blade lies just under the run-in, sending the
    # web into the press; as mix drops it swings up 50 degrees across the run-in, turning the web
    # off onto the dry path.
    px, py = 100, web_y + 9
    ang = -math.radians(6 + 50 * (1 - mix))
    tip = (px + 22 * math.cos(ang), py + 22 * math.sin(ang))
    nrm = (-math.sin(ang), math.cos(ang))
    f.poly([(px - 1.5 * nrm[0], py - 1.5 * nrm[1]), (tip[0] - 0.5 * nrm[0], tip[1] - 0.5 * nrm[1]),
            (tip[0] + 0.5 * nrm[0], tip[1] + 0.5 * nrm[1]), (px + 1.5 * nrm[0], py + 1.5 * nrm[1])],
           fill=G150, stroke="none", bound=True)
    f.circle(px, py, 3, fill=BLACK, stroke=G150, sw=HAIR)

    # Depth dimension on the right: extension lines from the two banks, a dimension line with
    # 45 degree tick ends (architectural), no figure: the header already shows crease.
    dx = 424
    f.line([(xs_up[-1] + R + 6, upper_y), (dx + 5, upper_y)], w=HAIR, colour=G50)
    f.line([(xs_lo[-1] + R + 6, lower_y), (dx + 5, lower_y)], w=HAIR, colour=G50, bound=True)
    f.line([(dx, upper_y), (dx, lower_y)], w=HAIR, colour=G125, bound=True)
    for yy, bnd in ((upper_y, False), (lower_y, True)):
        f.line([(dx - 3.5, yy + 3.5), (dx + 3.5, yy - 3.5)], w=HAIR, colour=G125, bound=bnd)
    return f


def main() -> None:
    frame = v4()
    (HERE / "clean.svg").write_text(frame.svg("v4 P1 engineering schematic · clean"))
    print(f"v4 clean: {frame.node} bound nodes")


if __name__ == "__main__":
    main()
