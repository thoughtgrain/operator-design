def n(v: float) -> str:
    s = f"{v:.2f}".rstrip("0").rstrip(".")
    return "0" if s in ("-0", "") else s


class Frame:
    def __init__(self) -> None:
        self.parts: list[str] = []
        self.node = 0

    def _id(self, bound: bool) -> str:
        if not bound:
            return ""
        i = self.node
        self.node += 1
        return f' id="bellows_node_{i}"'

    def poly(self, pts, fill="none", stroke=BRIGHT, sw=SUBJ, bound=False) -> None:
        pts = dedupe(pts)
        assert 3 <= len(pts) <= 64, len(pts)
        d = "M " + " L ".join(f"{n(x)} {n(y)}" for x, y in pts) + " Z"
        stroke_attr = f'stroke="{stroke}" stroke-width="{n(sw)}"' if stroke != "none" else 'stroke="none"'
        self.parts.append(f'<path{self._id(bound)} d="{d}" fill="{fill}" {stroke_attr}/>')

    def line(self, pts, w=HAIR, colour=G100, bound=False) -> None:
        """A polyline as a thin filled closed ribbon (constraints.md: never a stroke traced back)."""
        pts = dedupe(pts)
        for chunk in chunks(pts, 31):
            self.poly(ribbon(chunk, w), fill=colour, stroke="none", bound=bound)

    def circle(self, cx, cy, r, fill="#000000", stroke=G100, sw=HAIR, bound=False) -> None:
        stroke_attr = f'stroke="{stroke}" stroke-width="{n(sw)}"' if stroke != "none" else 'stroke="none"'
        self.parts.append(f'<circle{self._id(bound)} cx="{n(cx)}" cy="{n(cy)}" r="{n(r)}" fill="{fill}" {stroke_attr}/>')

    def rect(self, x, y, w, h, fill=G50, stroke="none", sw=HAIR, bound=False) -> None:
        self.poly([(x, y), (x + w, y), (x + w, y + h), (x, y + h)], fill=fill, stroke=stroke, sw=sw, bound=bound)

    def text(self, x, y, s, colour=G125, size=10) -> None:
        self.parts.append(f'<text transform="matrix(1 0 0 1 {n(x)} {n(y)})" fill="{colour}" stroke="none" '
                          f'font-family="{FONT}" font-size="{size}px">{s}</text>')

    def svg(self, title: str) -> str:
        head = header()
        palette = "\n  ".join(
            f'<path id="bellows_palette_{i}" d="M {700 + 10 * i} 300 L {704 + 10 * i} 300 L {704 + 10 * i} 304 Z" '
            f'fill="{c}" stroke="{c}" stroke-width="2"/>'
            for i, c in enumerate([BRIGHT, G150, G100, G75, G50, "#000000"]))
        body = "\n  ".join(self.parts)
        return (f'<svg xmlns="http://www.w3.org/2000/svg" width="{W}" height="{H}" viewBox="0 0 {W} {H}">\n'
                f'  <!-- bellows · subject pass 01 · {title} · rest (defaults, no notes). Generated by sketch.py -->\n'
                f'  <g id="preview_canvas">\n    <rect x="0" y="0" width="480" height="220" fill="#000000" stroke="none"/>\n  </g>\n'
                f'{head}\n  {palette}\n  {body}\n</svg>\n')


def dedupe(pts):
    out = []
    for p in pts:
        p = (round(p[0], 2), round(p[1], 2))
        if not out or math.dist(out[-1], p) >= 0.25:
            out.append(p)
    if len(out) > 2 and math.dist(out[0], out[-1]) < 0.25:
        out.pop()
    return out


def chunks(pts, size):
    if len(pts) <= size:
        yield pts
        return
    i = 0
    while i < len(pts) - 1:
        yield pts[i:i + size]
        i += size - 1


def ribbon(pts, w):
    """Offset a polyline both ways by w/2 with mitre joins (limited) and flat ends."""
    h = w / 2
    left, right = [], []
    for i, p in enumerate(pts):
        if i == 0:
            d = (pts[1][0] - p[0], pts[1][1] - p[1])
            nx, ny = norm((-d[1], d[0]))
            m = 1.0
        elif i == len(pts) - 1:
            d = (p[0] - pts[i - 1][0], p[1] - pts[i - 1][1])
            nx, ny = norm((-d[1], d[0]))
            m = 1.0
        else:
            a = norm((p[0] - pts[i - 1][0], p[1] - pts[i - 1][1]))
            b = norm((pts[i + 1][0] - p[0], pts[i + 1][1] - p[1]))
            n1, n2 = (-a[1], a[0]), (-b[1], b[0])
            nx, ny = norm((n1[0] + n2[0], n1[1] + n2[1]))
            cos = nx * n1[0] + ny * n1[1]
            m = min(1 / max(cos, 1e-3), 2.5)
        left.append((p[0] + nx * h * m, p[1] + ny * h * m))
        right.append((p[0] - nx * h * m, p[1] - ny * h * m))
    return left + right[::-1]


def norm(v):
    l = math.hypot(*v) or 1.0
    return (v[0] / l, v[1] / l)


def header() -> str:
    steps = ["#000000", G50, G75, G100, G125, G150, G175, BRIGHT]
    rows = [f'    <rect x="{60 * i}" y="0" width="60" height="20" fill="{c}" stroke="none"/>' for i, c in enumerate(steps)]
    for i, label in enumerate(["press", "reed", "leak", "choir"]):
        ink = "#CBCBCB" if i < 2 else "#000000"
        rows.append(f'    <text transform="matrix(1 0 0 1 {5 + 120 * i} 10)" fill="{ink}" stroke="none" '
                    f'font-family="{FONT}" font-size="10px">{label}</text>')
        rows.append(f'    <text transform="matrix(1 0 0 1 {65 + 120 * i} 17.44)" fill="{ink}" stroke="none" '
                    f'font-family="{FONT}" font-size="20px">{CAPTIONS[i]}</text>')
    return '  <g id="preview_header">\n' + "\n".join(rows) + "\n  </g>"


def circle_pts(cx, cy, r, k=48, a0=0.0, a1=2 * math.pi):
    return [(cx + r * math.cos(a0 + (a1 - a0) * i / k), cy + r * math.sin(a0 + (a1 - a0) * i / k)) for i in range(k + 1)]


# ---------------------------------------------------------------- v1 · P15 cell field, engineering schematic
def v1() -> Frame:
    """The wind chest as a schematic plenum of 24 px cells. Air under pressure is the lit mass,
    filled from the floor; the reed ports sit on the lid, the leak seam on the right wall."""
    f = Frame()
    cell, cols, rows = 24, 16, 6
    x0, y0 = 48, 54
    rng = random.Random(7)
    press, reed = DEFAULTS["press"], DEFAULTS["reed"]
    level = press * rows                      # 3 rows of air at 50 %
    run = 2 + round((1 - reed) * 2)           # stiffer (lower) reed: longer runs at the surface
    # Plenum wall (schematic: one hairline frame with a lid).
    f.line([(x0 - 6, y0 - 6), (x0 + cols * cell + 6, y0 - 6), (x0 + cols * cell + 6, y0 + rows * cell + 6),
            (x0 - 6, y0 + rows * cell + 6), (x0 - 6, y0 - 4)], w=LINE, colour=G100)
    # Reed ports on the lid: a slot drawn as a stub with its tongue.
    for k, px in enumerate((x0 + 5 * cell, x0 + 10 * cell)):
        f.line([(px, y0 - 6), (px, y0 - 16), (px + 30, y0 - 16), (px + 30, y0 - 6)], w=HAIR, colour=G100)
        f.line([(px + 4, y0 - 20), (px + 26, y0 - 23 - 8 * reed)], w=LINE,
               colour=G150 if k == 0 else G100, bound=True)
        f.text(px + 36, y0 - 9, "a" if k == 0 else "b")
    # Leak seam on the right wall (closed at leak 0): two short hairline lips.
    sx = x0 + cols * cell + 6
    f.line([(sx + 4, y0 + 52), (sx + 12, y0 + 52)], w=HAIR, colour=G100)
    f.line([(sx + 4, y0 + 60), (sx + 12, y0 + 60)], w=HAIR, colour=G100)
    # Cells: unlit = schematic hairline square; lit = solid run.
    heights = []
    c = 0
    while c < cols:
        width = min(run + rng.choice((-1, 0, 1)), cols - c)
        lift = level + rng.uniform(-1.3, 1.3)
        heights += [lift] * max(width, 1)
        c += max(width, 1)
    for cx in range(cols):
        for ry in range(rows):
            depth = rows - ry                  # 1 = floor row
            x, y = x0 + cx * cell, y0 + ry * cell
            if depth <= round(heights[cx]):
                f.rect(x, y, cell, cell, fill=BRIGHT, bound=True)
            else:
                f.rect(x + 4, y + 4, cell - 8, cell - 8, fill="#000000", stroke=G50, sw=HAIR, bound=True)
    # Dimension line for pressure (schematic): ticks at floor and at the fill level.
    dx = x0 - 22
    top = y0 + rows * cell - level * cell
    f.line([(dx, y0 + rows * cell), (dx, top)], w=HAIR, colour=G125)
    f.line([(dx - 4, top), (dx + 4, top)], w=HAIR, colour=G125)
    f.line([(dx - 4, y0 + rows * cell), (dx + 4, y0 + rows * cell)], w=HAIR, colour=G125)
    f.text(dx - 4, top - 6, "p")
    f.text(x0 - 6, y0 + rows * cell + 20, "wind chest")
    return f


# ---------------------------------------------------------------- v2 · P1 section, oscilloscope trace
def v2() -> Frame:
    """The bellows and its reed block cut open, plotted on a scope graticule. The pleats are a
    triangle trace; the reed tongue is a bright stroke over its slot."""
    f = Frame()
    gx0, gx1, gy0, gy1 = 20, 460, 34, 206
    # Graticule: 10 x 4 divisions, dim; centre lines carry minor ticks.
    for i in range(11):
        x = gx0 + i * (gx1 - gx0) / 10
        f.line([(x, gy0), (x, gy1)], w=HAIR, colour=G50)
    for j in range(5):
        y = gy0 + j * (gy1 - gy0) / 4
        f.line([(gx0, y), (gx1, y)], w=HAIR, colour=G50)
    cy = (gy0 + gy1) / 2
    for i in range(51):
        x = gx0 + i * (gx1 - gx0) / 50
        if i % 5:
            f.line([(x, cy - 2), (x, cy + 2)], w=HAIR, colour=G75)
    press, reed = DEFAULTS["press"], DEFAULTS["reed"]
    # Bellows: fixed board at left, moving board at right; press closes the pleats.
    bx0 = 52
    length = 250 - 110 * press                 # 195 px at 50 %
    bx1 = bx0 + length
    top, bot, depth, pleats = 70, 174, 12, 7
    f.line([(bx0, top - 10), (bx0, bot + 10)], w=SUBJ, colour=G150)
    f.line([(bx1, top - 10), (bx1, bot + 10)], w=SUBJ, colour=G150, bound=True)
    for edge, sign in ((top, -1), (bot, 1)):
        pts = []
        for k in range(pleats * 2 + 1):
            x = bx0 + length * k / (pleats * 2)
            pts.append((x, edge + (sign * depth if k % 2 else 0)))
        f.line(pts, w=SUBJ, colour=BRIGHT, bound=True)
    # Duct from the moving board to the reed plate.
    rx0, rx1, ry = 330, 446, 112
    f.line([(bx1, ry - 10), (rx0, ry - 10)], w=HAIR, colour=G125, bound=True)
    f.line([(bx1, ry + 10), (rx0, ry + 10)], w=HAIR, colour=G125, bound=True)
    # Reed plate a (slot as a gap in the plate), tongue a, then plate b below for the choir reed.
    for k, (py, colour, w) in enumerate(((ry, BRIGHT, SUBJ), (ry + 46, G125, LINE))):
        f.line([(rx0, py), (rx0 + 14, py)], w=LINE, colour=G150)
        f.line([(rx1 - 10, py), (rx1, py)], w=LINE, colour=G150)
        lift = 6 + 26 * reed if k == 0 else 4
        f.line([(rx0 + 14, py - 2), (rx1 - 14, py - 2 - lift)], w=w, colour=colour, bound=True)
        f.circle(rx0 + 14, py - 2, 2.5, fill=colour, stroke="none")
    f.line([(rx0, ry + 10), (rx0, ry + 46)], w=HAIR, colour=G125)
    f.text(gx0 + 4, gy1 - 6, "ch1  bellows")
    f.text(rx0, gy1 - 6, "ch2  reed")
    return f


# ---------------------------------------------------------------- v3 · P2 diagram + trace, typeset diagram
def reed_wave(t, reed):
    """A free reed's pulse-like wave: more upper partials as the reed opens."""
    s = 0.0
    for k in range(1, 7):
        s += math.sin(2 * math.pi * k * t) * (reed ** (k - 1)) / k
    return s


def v3() -> Frame:
    """Left, a textbook figure of the wind path: wedge bellows, wind trunk, two reeds a and b.
    Right, the output trace under its envelope."""
    f = Frame()
    press, reed, choir = DEFAULTS["press"], DEFAULTS["reed"], DEFAULTS["choir"]
    # Fig. 1: wedge reservoir hinged at the left; press lowers the top board (more weight, less volume).
    hx, hy, bx = 26, 160, 166
    ang = math.radians(26 - 18 * press)
    tx, ty = hx + (bx - hx) * math.cos(ang), hy - (bx - hx) * math.sin(ang)
    f.line([(hx, hy), (bx, hy)], w=LINE, colour=G150)
    f.line([(hx, hy), (tx, ty)], w=LINE, colour=G150, bound=True)
    f.line([(bx, hy), (bx, ty + 6)], w=HAIR, colour=G100, bound=True)
    f.circle(hx, hy, 3, fill="#000000", stroke=G150, sw=HAIR)
    # Weight on the top board, a typeset block with a leader to "p".
    wx, wy = hx + 0.62 * (tx - hx), hy + 0.62 * (ty - hy)
    f.poly([(wx - 12, wy - 2), (wx + 12, wy - 2), (wx + 12, wy - 16), (wx - 12, wy - 16)],
           fill=G50, stroke=G150, sw=HAIR, bound=True)
    f.text(wx - 3, wy - 22, "p")
    # Wind trunk to the reeds.
    f.line([(bx, 136), (206, 136), (206, 82)], w=HAIR, colour=G125)
    f.line([(bx, 146), (216, 146), (216, 82)], w=HAIR, colour=G125)
    for k, ry in enumerate((92, 116)):
        f.line([(198, ry), (224, ry)], w=LINE, colour=G150)
        f.line([(201, ry - 2), (221, ry - 2 - 4 - 8 * reed)], w=LINE, colour=G150 if k == 0 else G100, bound=True)
        f.text(230, ry + 3, "a" if k == 0 else "b")
    f.text(26, 196, "fig. 1  wind")
    # Fig. 2: output over one pressure sag, axis hairline and envelope.
    ax0, ax1, ay = 262, 462, 118
    f.line([(ax0, ay), (ax1, ay)], w=HAIR, colour=G75)
    f.line([(ax0, 52), (ax0, 184)], w=HAIR, colour=G75)
    for i in range(1, 5):
        x = ax0 + i * (ax1 - ax0) / 4
        f.line([(x, ay - 3), (x, ay + 3)], w=HAIR, colour=G100)
    amp = 22 + 36 * press
    cycles = 5
    env = []
    pts = []
    k = 120
    for i in range(k + 1):
        u = i / k
        sag = 1 - 0.18 * math.sin(math.pi * u) ** 2           # the bellows sags mid-stroke, recovers
        beat = 1 - choir * 0.8 * (0.5 + 0.5 * math.cos(2 * math.pi * 2 * u))
        e = amp * sag * beat
        env.append((ax0 + u * (ax1 - ax0), ay - e * 1.08 - 4))
        pts.append((ax0 + u * (ax1 - ax0), ay - e * reed_wave(cycles * u, reed) / 1.25))
    f.line(pts[::2], w=SUBJ, colour=BRIGHT, bound=True)
    f.line(env[::4], w=HAIR, colour=G100, bound=True)
    f.text(ax0, 202, "fig. 2  output")
    return f


# ---------------------------------------------------------------- v4 · P3 trace as subject, orthographic elevation
def v4() -> Frame:
    """The reed's wave drawn as a building is drawn in elevation: standing on a datum line,
    with the wind line (bellows pressure) above it, a level mark and a dimension."""
    f = Frame()
    press, reed, choir = DEFAULTS["press"], DEFAULTS["reed"], DEFAULTS["choir"]
    x0, x1, datum = 34, 446, 150
    # Ground: datum line and short station ticks below it, as an elevation's ground line.
    f.line([(14, datum), (466, datum)], w=HAIR, colour=G100)
    for i in range(12):
        x = x0 + i * (x1 - x0) / 11
        f.line([(x, datum + 6), (x, datum + 12)], w=HAIR, colour=G75)
    f.text(14, datum + 26, "datum")
    # The wind line: pressure over a held stroke, sagging and recovering. Its height is press.
    wind_h = 30 + 70 * press
    wind = []
    for i in range(33):
        u = i / 32
        sag = 1 - 0.22 * math.sin(math.pi * u) ** 1.5
        wind.append((x0 + u * (x1 - x0), datum - wind_h * sag))
    f.line(wind, w=LINE, colour=G125, bound=True)
    # Level mark on the wind line at the left: a small open triangle on a stem, labelled.
    lx, ly = 22, wind[0][1]
    f.poly([(lx - 5, ly - 8), (lx + 5, ly - 8), (lx, ly - 1)], fill="#000000", stroke=G125, sw=HAIR)
    f.text(lx - 6, ly - 13, "wind")
    # The trace: reed wave rectified upward from the datum, as a skyline, its envelope the wind line.
    cycles = 9
    pts, ghost = [], []
    k = 240
    for i in range(k + 1):
        u = i / k
        x = x0 + u * (x1 - x0)
        h_env = wind_h * (1 - 0.22 * math.sin(math.pi * u) ** 1.5) * 0.92
        w = reed_wave(cycles * u, reed)
        w2 = reed_wave(cycles * u * (1 + choir * 0.03), reed)
        pts.append((x, datum - h_env * (0.5 + 0.5 * w / 1.25)))
        ghost.append((x, datum - h_env * (0.5 + 0.5 * w2 / 1.25)))
    f.line(ghost[::2], w=LINE, colour=G75, bound=True)
    # Mullions: vertical hairlines from the datum up to the wave every 12 px, so it stands as a facade.
    for i in range(1, 35):
        j = round(i * k / 35)
        x, y = pts[j]
        if datum - y > 8:
            f.line([(x, datum - 1), (x, y + 3)], w=HAIR, colour=G75)
    f.line(pts[::2], w=SUBJ, colour=BRIGHT, bound=True)
    # Dimension at the right: extension lines and the height of the wind line at the right edge.
    dx = 458
    ytop = wind[-1][1]
    f.line([(dx, datum), (dx, ytop)], w=HAIR, colour=G125, bound=True)
    f.line([(dx - 4, ytop), (dx + 4, ytop)], w=HAIR, colour=G125, bound=True)
    f.line([(dx - 4, datum), (dx + 4, datum)], w=HAIR, colour=G125)
    # Breath (leak) lies along the datum as a band of grass-like strokes; none at leak 0.
    f.text(x0, 204, "reed a  elevation")
    return f


# ---------------------------------------------------------------- v5 · P12 orrery, survey plan
def v5() -> Frame:
    """Plan view: the reed's cycle as a surveyed ring round the wind chest, reed a and reed b
    as two stations on it. Choir opens the angle between them: the beat is their phase gap."""
    f = Frame()
    press, reed, choir, leak = DEFAULTS["press"], DEFAULTS["reed"], DEFAULTS["choir"], DEFAULTS["leak"]
    cx, cy = 232, 120
    # Survey grid crosses every 80 px, dim.
    for gx in range(40, 480, 80):
        for gy in range(40, 220, 80):
            if math.dist((gx, gy), (cx, cy)) < 100:
                continue
            f.line([(gx - 4, gy), (gx + 4, gy)], w=HAIR, colour=G50)
            f.line([(gx, gy - 4), (gx, gy + 4)], w=HAIR, colour=G50)
    # Wind chest at the centre: a surveyed parcel (closed boundary).
    f.poly([(cx - 16, cy - 12), (cx + 18, cy - 14), (cx + 16, cy + 12), (cx - 14, cy + 14)],
           fill=G50, stroke=G150, sw=LINE)
    # The ring: radius from press.
    r = 52 + 40 * press
    f.circle(cx, cy, r, fill="none", stroke=G125, sw=LINE, bound=True)
    # Chainage ticks round the ring: count from reed.
    ticks = round(12 + 24 * reed)
    for i in range(ticks):
        a = 2 * math.pi * i / ticks
        f.line([(cx + (r + 3) * math.cos(a), cy + (r + 3) * math.sin(a)),
                (cx + (r + 9) * math.cos(a), cy + (r + 9) * math.sin(a))], w=HAIR, colour=G100, bound=True)
    # Bearing from the chest to station a, and the two stations (b sits on a at choir 0, drawn behind).
    a_ang = math.radians(-35)
    b_ang = a_ang + math.radians(150 * choir)
    sa = (cx + r * math.cos(a_ang), cy + r * math.sin(a_ang))
    sb = (cx + r * math.cos(b_ang), cy + r * math.sin(b_ang))
    f.line([(cx + 18 * math.cos(a_ang), cy + 18 * math.sin(a_ang)), sa], w=HAIR, colour=G100, bound=True)
    f.circle(*sb, 7, fill="#000000", stroke=G150, sw=LINE, bound=True)
    f.circle(*sa, 5, fill=BRIGHT, stroke="none", bound=True)
    f.text(sa[0] + 12, sa[1] - 6, "a  b")
    # Scale bar (survey plan furniture), bottom right: alternate filled and open segments.
    bx, by = 366, 196
    for i in range(4):
        f.rect(bx + 22 * i, by, 22, 5, fill=G100 if i % 2 == 0 else "#000000", stroke=G100, sw=HAIR)
    f.text(bx, by - 6, "0")
    f.text(bx + 84, by - 6, "1 st")
    f.text(16, 210, "plan  wind chest")
    return f


