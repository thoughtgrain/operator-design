#!/usr/bin/env python3
"""Bell, refined rest and control frames from revision pass 02's v5 (looking up into the mouth).

    python3 screens/bell/frames/build.py

The owner's note on v5: keep it, remove the hatched background, and give it some
simple environmental grounding. So the ground is black, and the bell is placed under
water by quiet cues drawn in the same hidden-line language, from the same 3D model
and the same camera as everything else.

Writes into this folder:
  rest.svg/png                      every control at its default
  <control>-0/50/100.svg/png        one control moved, the rest at their defaults
  grounding/<cue>.svg               the cues tried, one rest frame each (scratch, tiled
                                    into grounding.png and then removed)
  grounding.png, before-after.png, contact.png, sweep.gif

The model (Bell, Cam, hull, hatch, ribbon lines) is pass 02's sketch.py, imported as is;
this file only adds the grounding cues, the clapper's swing and the header captions.
Grey only, never red. Nothing in the drawing is text; the stock header is the only text.
"""
from __future__ import annotations

import importlib.util
import math
import shutil
import subprocess
import sys
from pathlib import Path

sys.dont_write_bytecode = True
HERE = Path(__file__).resolve().parent
SKETCH = HERE.parent / "passes" / "02-revision" / "sketch.py"
_spec = importlib.util.spec_from_file_location("bell_sketch", SKETCH)
S = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(S)

W, H, TOP = S.W, S.H, S.TOP
BRIGHT, G175, G150, G125, G100, G75, G50, BLACK = (S.BRIGHT, S.G175, S.G150, S.G125, S.G100,
                                                   S.G75, S.G50, S.BLACK)
HAIR, LINE, SUBJ = S.HAIR, S.LINE, S.SUBJ
FONT = S.FONT

CONTROLS = ["depth", "air", "knee", "gain"]
DEFAULTS = {"depth": 0.25, "air": 0.5, "knee": 0.25, "gain": 0.25}


# ---------------------------------------------------------------- header captions (definition.json mappings)
def caption(ctrl: str, v: float) -> str:
    """What the stock header prints for this control: ratio / duration formats, <= ~5 characters."""
    if ctrl == "depth":                       # linear 0..48, ratio
        x = 48 * v
        return f"{x:.0f}" if abs(x - round(x)) < 1e-6 else f"{x:.1f}"
    if ctrl == "air":                         # exponential 0.02..2 s, duration
        t = 0.02 * 100 ** v
        return f"{t * 1000:.0f}ms" if t < 0.1 else f"{t:.1f}s"
    if ctrl == "knee":                        # linear 0..24, ratio
        return f"{24 * v:.1f}"
    g = 16 ** v                               # exponential 1..16, ratio
    return f"{g:.2f}" if g < 10 else f"{g:.1f}"


def header(p) -> str:
    steps = [BLACK, G50, G75, G100, G125, G150, G175, BRIGHT]
    rows = [f'    <rect x="{60 * i}" y="0" width="60" height="20" fill="{c}" stroke="none"/>'
            for i, c in enumerate(steps)]
    for i, label in enumerate(CONTROLS):
        ink = "#CBCBCB" if i < 2 else BLACK
        rows.append(f'    <text transform="matrix(1 0 0 1 {5 + 120 * i} 10)" fill="{ink}" stroke="none" '
                    f'font-family="{FONT}" font-size="10px">{label}</text>')
        rows.append(f'    <text transform="matrix(1 0 0 1 {65 + 120 * i} 17.44)" fill="{ink}" stroke="none" '
                    f'font-family="{FONT}" font-size="20px">{caption(label, p[label])}</text>')
    return '  <g id="preview_header">\n' + "\n".join(rows) + "\n  </g>"


def svg(f: S.Frame, p, title: str) -> str:
    palette = "\n  ".join(
        f'<path id="bell_palette_{i}" d="M {700 + 10 * i} 300 L {704 + 10 * i} 300 L {704 + 10 * i} 304 Z" '
        f'fill="{c}" stroke="{c}" stroke-width="2"/>'
        for i, c in enumerate([BRIGHT, G150, G125, G100, G75, G50, BLACK]))
    body = "\n  ".join(f.parts)
    return (f'<svg xmlns="http://www.w3.org/2000/svg" width="{W}" height="{H}" viewBox="0 0 {W} {H}">\n'
            f'  <!-- bell · refined v5 · {title}. Generated by build.py -->\n'
            f'  <g id="preview_canvas">\n    <rect x="0" y="0" width="480" height="220" fill="#000000" stroke="none"/>\n  </g>\n'
            f'{header(p)}\n  {palette}\n  {body}\n</svg>\n')


# ---------------------------------------------------------------- scene
# v5's camera, unchanged: from below and in front of the bell, looking up into its mouth.
CAM_POS, CAM_LOOK = (0, -4.6, -4.4), (0, 0, -2.0)
ZRIM = lambda d: -(S.Bell.H + 0.15 + 0.9 * d)       # depth: rim 1.37 -> 2.27 below the model origin
FIT_BOX = (110, 40, 370, 207)                         # bell's travel over depth 0..1; room above for the cable
SURFACE_Y = 27                                        # where the surface right over the bell lands on screen

CLAPPER_L = 0.78          # pivot to ball centre, rim radius = 1
BALL_R = 0.11
SWING = 46                # gain: the clapper drawn back 0 -> 46 degrees


def lip_of(g):
    """gain: the sound-bow's flare at the lip, 0.02 -> 0.24 of the rim radius (the rim's radius
    grows about 15 %, the band between the bow's hoop and the rim widens)."""
    return 0.02 + 0.22 * g


class DomedBell(S.Bell):
    """Pass 02's bell, plus a crown that domes up with the knee: at a hard knee the crown is a flat
    top on a sharp shoulder, at a soft knee the shoulder's fillet is full and the crown rises into a
    round dome (0.42 of the rim radius). From below, the crown is only seen in the silhouette, so
    the fillet alone moved it by a few pixels; the dome gives the knee a shape change you can see."""
    DOME = 0.42

    def __init__(self, z0, knee=DEFAULTS["knee"], air=DEFAULTS["air"], lip=None, gain=DEFAULTS["gain"]):
        lip = lip_of(gain) if lip is None else lip
        super().__init__(z0, knee=knee, air=air, lip=lip)
        hd, r0 = self.DOME * knee, self.RT + 0.12
        bump = lambda r, R: hd * max(0.0, 1 - (r / R) ** 2)
        self.outer = [(r, z + bump(r, r0), nr, nz) for r, z, nr, nz in self.outer]
        self.inner = [(r, z + bump(r, r0 - self.WALL), nr, nz) for r, z, nr, nz in self.inner]

    def crown(self):
        return (self.x0, self.y0, self.z0 + self.s * self.outer[0][1])


def make_cam():
    cam = S.Cam(CAM_POS, CAM_LOOK, persp=True)
    ends = DomedBell(ZRIM(0), knee=1, gain=1).shell() + DomedBell(ZRIM(1), knee=1, gain=1).shell()
    cam.fit(ends, FIT_BOX)
    # the sea's surface: the height whose point right over the bell lands at SURFACE_Y
    lo, hi = 0.0, 20.0
    for _ in range(60):
        mid = (lo + hi) / 2
        if cam((0, 0, mid))[1] > SURFACE_Y:
            lo = mid
        else:
            hi = mid
    return cam, (lo + hi) / 2


CAM, ZS = make_cam()


def wavy(cam, yw, x0, x1, z, amp=0.05, k=3.1, n=40):
    """A ripple crest on the surface plane: a line along x at y = yw, meandering a little in y."""
    return [cam((x0 + (x1 - x0) * i / n, yw + amp * math.sin(k * (x0 + (x1 - x0) * i / n)), z))
            for i in range(n + 1)]


def scene(p, cues=("cable", "bubbles")) -> S.Frame:
    f = S.Frame()
    cam = CAM
    b = DomedBell(ZRIM(p["depth"]), knee=p["knee"], air=p["air"], gain=p["gain"])
    out = S.thin(S.outline_of(cam, b))
    top = min(y for _, y in out)

    # ---- behind the bell
    if "surface" in cues:
        # the sea's surface far above, seen from underneath: ripple crests on its plane, evenly
        # spaced in the world, so they close up and shorten as they recede (toward the bell)
        for yw, half, col in ((0.0, 2.3, G75), (0.9, 2.0, G50), (2.2, 1.7, G50)):
            S.draw_runs(f, [wavy(cam, yw, -half, half, ZS)], colour=col)
    if "shafts" in cues:
        # light from the surface: three straight shafts, sun a little off the zenith
        d = S.unit((0.16, 0.08, -1.0))
        for x, y in ((-2.0, 0.6), (-1.35, 1.4), (1.75, 0.9)):
            a = (x, y, ZS)
            q = S.add(a, S.mul(d, ZS - ZRIM(1) + 0.4))
            pa, pb = S.clip_box(cam(a), cam(q), (0, 26, W, 214))
            if pa:
                f.line([pa, pb], w=HAIR, colour=G50)
    if "cable" in cues:
        # the cable it hangs from, straight up from the crown's eye; it meets the surface if that's
        # drawn, otherwise it leaves the picture just under the header
        ya = SURFACE_Y if "surface" in cues else 25
        f.line([(W / 2, ya), (W / 2, top + 6)], w=HAIR, colour=G100)

    # ---- the bell: dark body, hidden-line exterior outside the mouth
    f.body(out, stroke=G100, sw=HAIR)
    rim_poly = [cam(b.P(b.outer[-1][0], 0, 2 * math.pi * i / 60)) for i in range(60)]
    mouth = [cam(b.P(b.inner[-1][0], 0, 2 * math.pi * i / 60)) for i in range(60)]
    outside = lambda pt, nrm, th: cam.facing(pt, nrm) > 0.05 and not S.inside(cam(pt), mouth)
    s0, s1, _ = b.shoulder_idx()
    for idx in (s0, s1, s1 + 1, s1 + 2, s1 + 3):
        S.draw_runs(f, S.runs(cam, b.ring(b.outer, idx, 96), outside), colour=G100)
    # the sound-bow: its upper hoop, so the flared band above the rim (gain) reads
    S.draw_runs(f, S.runs(cam, b.ring(b.outer, len(b.outer) - 3, 96), outside), w=LINE, colour=G125)
    for i in range(16):
        th = 2 * math.pi * (i + 0.5) / 16
        S.draw_runs(f, S.runs(cam, b.meridian(b.outer[1:s1 + 4], th),
                              lambda pt, nrm, th: cam.facing(pt, nrm) > 0.3 and not S.inside(cam(pt), mouth)),
                    colour=G75)

    # ---- inside the mouth: hoops of the air pocket, the water's surface, the clapper
    inn = lambda pt, nrm, th: S.inside(cam(pt), mouth)
    for z in (b.zw + 0.25, b.zw + 0.55):
        if z < b.inner[0][1] - 0.1:
            S.draw_runs(f, S.runs(cam, b.ring(b.inner, z, 96), inn), colour=G50)
    piv = b.P(0, b.H - b.WALL, 0)
    ang = math.radians(SWING * p["gain"])
    ball = S.add(piv, (CLAPPER_L * math.sin(ang), 0, -CLAPPER_L * math.cos(ang)))
    bp, r_px = cam(ball), BALL_R * cam.ppu(ball)
    ball_in_air = ball[2] > b.z0 + b.zw            # above the waterline: seen through the water's surface
    if ang > 0.02:                                  # its travel from plumb: the hidden-line convention
        arc = [cam(S.add(piv, (CLAPPER_L * math.sin(a), 0, -CLAPPER_L * math.cos(a))))
               for a in [ang * i / 16 for i in range(17)]]
        f.dashed(arc, dash=3, gap=3, colour=G75)
    # rod: pivot to the ball's edge
    rod_end = (bp[0] - (bp[0] - cam(piv)[0]) * r_px / max(math.dist(bp, cam(piv)), 1),
               bp[1] - (bp[1] - cam(piv)[1]) * r_px / max(math.dist(bp, cam(piv)), 1))
    f.line([cam(b.P(0, b.inner[0][1], 0)), cam(piv), rod_end], w=HAIR, colour=G125)   # staple, then rod
    if ball_in_air:
        f.circle(bp[0], bp[1], r_px, fill=BLACK, stroke=G150, sw=LINE)
    wl = [cam(pt) for pt, _, _ in b.ring(b.inner, b.zw, 72)]
    f.hatch(S.thin(wl, 1.5), spacing=4, colour=G75, flip=True)
    f.line(wl, w=LINE, colour=G125)
    if not ball_in_air:
        f.circle(bp[0], bp[1], r_px, fill=BLACK, stroke=G150, sw=LINE)

    # ---- in front of the bell
    if "bubbles" in cues:
        # air escaping under the lip on the right, rising past the wall and growing as it rises
        th = -0.32
        r0 = b.outer[-1][0] + 0.07
        for dz, dr, rr in ((0.18, 0.00, 0.034), (0.46, 0.07, 0.044), (0.80, 0.01, 0.052), (1.20, 0.10, 0.062)):
            c = b.P(r0 + dr, dz, th)
            q = cam(c)
            f.circle(q[0], q[1], max(2.0, rr * cam.ppu(c)), fill=BLACK, stroke=G125, sw=HAIR)
    if "weight" in cues:
        # one ballast weight hung below the lip on the left, on a short line
        th = math.pi + 0.45
        rl = b.outer[-1][0] * 0.94
        a = b.P(rl, 0, th)
        wtop = S.add(a, (0, 0, -0.42))
        f.line([cam(a), cam(wtop)], w=HAIR, colour=G100)
        cyl = [cam(S.add(wtop, (0.11 * math.cos(t), 0.11 * math.sin(t), dz)))
               for t in [2 * math.pi * i / 24 for i in range(24)] for dz in (0, -0.2)]
        f.body(S.hull(cyl), stroke=G125, sw=HAIR)
        f.line([cam(S.add(wtop, (0.11 * math.cos(t), 0.11 * math.sin(t), 0)))
                for t in [math.pi + math.pi * i / 16 for i in range(17)]], w=HAIR, colour=G100)

    # ---- the rim, depth's leading edge, brightest
    f.poly(rim_poly, fill="none", stroke=BRIGHT, sw=SUBJ)
    return f


# ---------------------------------------------------------------- output
KEPT = ("cable", "bubbles")
CUES = [("cable", ("cable",)), ("surface", ("surface",)), ("bubbles", ("bubbles",)),
        ("shafts", ("shafts",)), ("weight", ("weight",)), ("cable + surface", ("cable", "surface"))]


def render(svg_path: Path, png_path: Path | None = None) -> Path:
    png_path = png_path or svg_path.with_suffix(".png")
    subprocess.run(["rsvg-convert", str(svg_path), "-o", str(png_path)], check=True)
    return png_path


def write(name: str, p, cues=KEPT, title="", d=HERE) -> Path:
    path = d / f"{name}.svg"
    path.write_text(svg(scene(p, cues), p, title or name))
    render(path)
    return path


def main() -> None:
    from PIL import Image, ImageDraw, ImageFont

    write("rest", DEFAULTS, title="rest (defaults)")
    for c in CONTROLS:
        for v in (0, 50, 100):
            p = dict(DEFAULTS, **{c: v / 100})
            write(f"{c}-{v}", p, title=f"{c} {v}")

    try:
        font = ImageFont.truetype("DejaVuSans.ttf", 13)
    except OSError:
        font = ImageFont.load_default()

    def label_tile(img, text, x, y, colour=(150, 150, 150)):
        ImageDraw.Draw(img).text((x, y), text, fill=colour, font=font)

    # grounding.png: each cue alone at rest, then the kept pair, kept one marked outside its frame
    gdir = HERE / "_grounding"
    gdir.mkdir(exist_ok=True)
    tiles = CUES + [("cable + bubbles", KEPT)]
    gap, lab = 24, 26
    cols = 4
    rows = math.ceil(len(tiles) / cols)
    sheet = Image.new("RGB", (cols * W + (cols + 1) * gap, rows * (H + lab) + (rows + 1) * gap), (24, 24, 24))
    for i, (name, cues) in enumerate(tiles):
        path = write(name.replace(" ", "").replace("+", "_").replace(":", ""), DEFAULTS, cues, f"grounding {name}", gdir)
        im = Image.open(path.with_suffix(".png")).convert("RGB")
        x = gap + (i % cols) * (W + gap)
        y = gap + (i // cols) * (H + lab + gap)
        sheet.paste(im, (x, y))
        kept = cues == KEPT
        if kept:
            dr = ImageDraw.Draw(sheet)
            dr.rectangle((x - 8, y - 8, x + W + 7, y + H + 7), outline=(205, 205, 205), width=2)
        label_tile(sheet, ("kept: " if kept else "") + name, x, y + H + 8,
                   (220, 220, 220) if kept else (140, 140, 140))
    sheet.save(HERE / "grounding.png")
    shutil.rmtree(gdir)

    # before-after.png: pass 02 v5 as picked, and the refined rest, both 1:1
    before = Image.open(HERE.parent / "passes" / "02-revision" / "v5" / "rest.png").convert("RGB")
    after = Image.open(HERE / "rest.png").convert("RGB")
    ba = Image.new("RGB", (2 * W + 3 * gap, H + lab + 2 * gap), (24, 24, 24))
    ba.paste(before, (gap, gap))
    ba.paste(after, (2 * gap + W, gap))
    label_tile(ba, "before: pass 02 v5", gap, gap + H + 8)
    label_tile(ba, "after: refined rest", 2 * gap + W, gap + H + 8, (220, 220, 220))
    ba.save(HERE / "before-after.png")

    # contact.png: rest, then one row per control at 0 / 50 / 100, all 1:1
    rows = [[("rest", "rest")]] + [[(f"{c}-{v}", f"{c} {v}") for v in (0, 50, 100)] for c in CONTROLS]
    cs = Image.new("RGB", (3 * W + 4 * gap, len(rows) * (H + lab) + (len(rows) + 1) * gap), (24, 24, 24))
    for r, row in enumerate(rows):
        for c, (name, text) in enumerate(row):
            x, y = gap + c * (W + gap), gap + r * (H + lab + gap)
            cs.paste(Image.open(HERE / f"{name}.png").convert("RGB"), (x, y))
            label_tile(cs, text, x, y + H + 8)
    cs.save(HERE / "contact.png")

    # sweep.gif: each control turned 0 -> 100 -> default in turn, 1:1. No live input on an effect page,
    # so this is the only motion the screen has: a control easing as it turns
    frames, durs = [], []
    tmp = HERE / "_sweep"
    tmp.mkdir(exist_ok=True)
    k = 0
    for c in CONTROLS:
        d0 = DEFAULTS[c]
        path = [d0 + (0 - d0) * i / 8 for i in range(9)] + [i / 24 for i in range(1, 25)] + \
               [1 + (d0 - 1) * i / 12 for i in range(1, 13)]
        for j, v in enumerate(path):
            p = dict(DEFAULTS, **{c: v})
            sp = tmp / f"{k:04d}.svg"
            sp.write_text(svg(scene(p, KEPT), p, "sweep"))
            frames.append(Image.open(render(sp)).convert("RGB"))
            durs.append(500 if j in (0, 8, 32) else 50)
            k += 1
    frames[0].save(HERE / "sweep.gif", save_all=True, append_images=frames[1:], duration=durs, loop=0)
    shutil.rmtree(tmp)
    print("wrote rest, 12 control frames, grounding.png, before-after.png, contact.png, sweep.gif")


if __name__ == "__main__":
    main()
